// Writes public/THIRD_PARTY_NOTICES.txt: every npm package and Rust crate the
// app ships with, its license, and the license texts their authors include.
// Run before a release (`npm run notices`) and commit the result. The web
// build copies it from public/ into dist/, and the desktop app bundles it as a
// resource (tauri.conf.json).

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TAURI_DIR = join(ROOT, "src-tauri");
const OUT = join(ROOT, "public", "THIRD_PARTY_NOTICES.txt");

/** The platforms the desktop app is released for: only their crates ship. */
const RUST_TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin"];
/** This app's own crates, not third-party. */
const OWN_CRATES = new Set(["nuthatch"]);

const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright)([-._].*)?$/i;

function run(cmd, args, cwd = ROOT) {
  return execFileSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 512 * 1024 * 1024 });
}

/** The license and notice files a package ships, read as text. */
function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => LICENSE_FILE.test(name))
    .sort()
    .map((name) => readFileSync(join(dir, name), "utf8").trim())
    .filter(Boolean);
}

function repoUrl(repository) {
  const url = typeof repository === "string" ? repository : repository?.url;
  return (url ?? "").replace(/^git\+/, "").replace(/\.git$/, "");
}

/** The npm packages in the production dependency tree. */
function npmPackages() {
  const dirs = run("npm", ["ls", "--omit=dev", "--all", "--parseable"]).trim().split("\n").slice(1);
  return [...new Set(dirs)].map((dir) => {
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    return {
      source: "npm",
      name: pkg.name,
      version: pkg.version,
      license: pkg.license ?? "",
      url: repoUrl(pkg.repository) || pkg.homepage || "",
      texts: licenseTexts(dir),
    };
  });
}

/** The Rust crates linked into the desktop app on the release targets. */
function rustCrates() {
  const ids = new Set();
  for (const target of RUST_TARGETS) {
    const tree = run("cargo", ["tree", "--locked", "-e", "normal", "--prefix", "none", "--format", "{p}", "--target", target], TAURI_DIR);
    for (const line of tree.split("\n")) {
      const match = /^(\S+) v(\S+)/.exec(line);
      if (match && !OWN_CRATES.has(match[1])) ids.add(`${match[1]} ${match[2]}`);
    }
  }
  const meta = JSON.parse(run("cargo", ["metadata", "--locked", "--format-version", "1"], TAURI_DIR));
  return meta.packages
    .filter((p) => ids.has(`${p.name} ${p.version}`))
    .map((p) => ({
      source: "rust",
      name: p.name,
      version: p.version,
      license: p.license ?? (p.license_file ? "see license file" : ""),
      url: p.repository ?? p.homepage ?? "",
      texts: licenseTexts(dirname(p.manifest_path)),
    }));
}

function byName(a, b) {
  return a.source.localeCompare(b.source) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true });
}

function build() {
  const packages = [...npmPackages(), ...rustCrates()].sort(byName);
  const label = (p) => `${p.name} ${p.version}`;

  // Many packages carry the same license text (most Rust crates share the
  // MIT and Apache texts), so each distinct text is written once, followed by
  // the packages it covers.
  const users = new Map();
  for (const p of packages) {
    for (const text of p.texts) {
      const key = text.replace(/\s+/g, " ");
      const entry = users.get(key) ?? { text, packages: [] };
      entry.packages.push(label(p));
      users.set(key, entry);
    }
  }
  const missing = packages.filter((p) => p.texts.length === 0);

  const lines = [
    "THIRD-PARTY NOTICES FOR NUTHATCH",
    "",
    "nuthatch includes the third-party software listed below. Each package keeps",
    "its own license; the license texts follow the list, each with the packages",
    "it covers. Generated by scripts/third-party-notices.mjs; don't edit by hand.",
    "",
    "",
    `PACKAGES (${packages.length})`,
    "",
    ...packages.map((p) => `${p.source.padEnd(5)} ${label(p).padEnd(48)} ${p.license}${p.url ? `  ${p.url}` : ""}`),
  ];
  if (missing.length) {
    lines.push(
      "",
      "These packages include no license file; their license is the one named in",
      "the list above, published at their repository:",
      "",
      ...missing.map((p) => `  ${label(p)}  ${p.license}  ${p.url}`),
    );
  }
  lines.push("", "", "LICENSE TEXTS");
  for (const { text, packages: covered } of [...users.values()].sort((a, b) => a.packages[0].localeCompare(b.packages[0]))) {
    lines.push("", "=".repeat(78), `Used by: ${covered.join(", ")}`, "=".repeat(78), "", text);
  }
  writeFileSync(OUT, lines.join("\n") + "\n");
  console.log(`${OUT}: ${packages.length} packages, ${users.size} license texts, ${missing.length} without a license file`);
}

build();
